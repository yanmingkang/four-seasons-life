export function eventCopy(event){
  const base=event.dynamicScene?event.scene.split('\n\n')[0]:event.scene;
  // Respect alternate/authored test scenes instead of silently replacing them.
  if(base!==EVENTS[event.number-1]?.scene)return {scene:base,detail:'',background:''};
  const detail=isKeyEvent(event)?KEY_DETAILS[event.number]:'';
  return {scene:detail?base:SCENES[event.number]||base,detail,background:detail?'':SCENES[event.number]?base:''};
}
export function feedbackShort(record){
  const event=EVENTS.find(e=>e.id===record.eventId),option=event?.options[record.choice];
  // Resolved success/failure branches and future custom text remain authoritative.
  if(!event||isKeyEvent(event)||option?.threshold||!record.result.startsWith(option?.result||'\0'))return '';
  return FEEDBACK[event.number]?.[record.choice]||'';
}
