export const EVENTS = BASE_EVENTS.map(event=>{
  const [prompt, descriptions] = CHOICE_TEXT[event.number];
  const options = [...event.options,...MORE_CHOICES[event.number]];
  if(options.length!==3 || descriptions.length!==3) throw new Error(`地点 ${event.number} 需要三种完整选择`);
  return {...event,sources:[...(EVENT_GROUNDING[event.id]?.sourceIds??event.sources)],prompt,isChoice:true,options:options.map((option,index)=>({...option,description:descriptions[index]}))};
});

